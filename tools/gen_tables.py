"""Generate editor/Tables.cs (name tables) from community ID lists.

    python -I tools/gen_tables.py <ff12tza-utils docs dir> <rich editor xml dir>

Sources:
- ff12tza-utils by LuminaSapphira (MIT): docs/identifiers/*.md and
  docs/license_ids.tsv. Gives the PC (Zodiac Age) names for items,
  equipment, loot, key items, magicks, technicks and licenses.
- The XML data files shipped with the PS2 "International Zodiac Job System"
  rich save editor (ff12doc): gambits.xml, gambitactions.xml, equipment.xml.
  Gives gambit targets, gambit actions and equipment types. The PC version
  kept the IZJS IDs.

The script reads the md tables by file name, so point it at a directory
holding the files named as below (flattened copies are fine).
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

MD_FILES = {
    "items": ["docs_identifiers_inventory_Items.md", "Items.md"],
    "equipment": ["inv_Equipment.md", "Equipment.md"],
    "loot": ["inv_Loot.md", "Loot.md"],
    "keyitems": ["inv_Key_Items.md", "Key Items.md"],
    "magicks": ["inv_Magicks.md", "Magicks.md"],
    "technicks": ["inv_Technicks.md", "Technicks.md"],
}

SINGULAR = {
    "Swords": "Sword", "Great Swords": "Greatsword", "Katana": "Katana", "Ninja Swords": "Ninja Sword",
    "Spears": "Spear", "Poles": "Pole", "Bows": "Bow", "Crossbows": "Crossbow", "Guns": "Gun",
    "Axes": "Axe", "Hammers": "Hammer", "Daggers": "Dagger", "Rods": "Rod", "Staves": "Staff",
    "Maces": "Mace", "Measures": "Measure", "Hand-bombs": "Hand-bomb", "Arrows": "Arrows",
    "Bolts": "Bolts", "Shot": "Shot", "Bombs": "Bombs", "Shields": "Shield",
    "Light Helms": "Light helm", "Mystic Helms": "Mystic helm", "Heavy Helms": "Heavy helm",
    "Light Armor": "Light armor", "Mystic Armor": "Mystic armor", "Heavy Armor": "Heavy armor",
    "Accessory": "Accessory",
}


def read_md(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\|\s*(\d+)\s*\|\s*(.*?)\s*\|", line)
        if m:
            out[int(m.group(1))] = m.group(2)
    return out


def find(d, names):
    for n in names:
        p = os.path.join(d, n)
        if os.path.exists(p):
            return p
    raise SystemExit("missing %s in %s" % (names[0], d))


def xml_items(path):
    """Yield (group path, id, name) for every <Item> in a rich editor XML file."""
    def walk(e, groups):
        for c in e:
            if c.tag == "Item":
                yield groups, int(c.get("ID")), c.get("Name")
            elif c.tag in ("Class", "Group"):
                yield from walk(c, groups + [c.get("Name")])
    yield from walk(ET.parse(path).getroot(), [])


def clean(name):
    return "" if name in ("Reserve", "No Name", "") else name


def table(names, base, count):
    return [clean(names.get(base + i, "")) for i in range(count)]


def cs_array(name, values):
    body = ",\n".join("            " + ", ".join(cs_str(v) for v in values[i:i + 6]) for i in range(0, len(values), 6))
    return "        public static readonly string[] %s = {\n%s\n        };\n" % (name, body)


def cs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    md_dir, xml_dir = sys.argv[1], sys.argv[2]
    md = {k: read_md(find(md_dir, v)) for k, v in MD_FILES.items()}

    licenses = {}
    for line in open(find(md_dir, ["docs_license_ids.tsv", "license_ids.tsv"]), encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if parts[0].isdigit():
            licenses[int(parts[0])] = parts[2]

    eq_type = {}
    for groups, i, _ in xml_items(os.path.join(xml_dir, "equipment.xml")):
        if groups[-1] in SINGULAR:
            eq_type[i] = SINGULAR[groups[-1]]
    gambits = {i: n for _, i, n in xml_items(os.path.join(xml_dir, "gambits.xml"))}
    actions = {i: n for _, i, n in xml_items(os.path.join(xml_dir, "gambitactions.xml"))}
    # Prefer the PC names for the action IDs that mirror inventory lists.
    for i, n in md["magicks"].items():
        actions[i - 0x3000] = n
    for i, n in md["items"].items():
        if clean(n):
            actions[82 + i] = n
    for i, n in md["technicks"].items():
        actions[158 + (i - 0x4000)] = n

    n_equip = max(md["equipment"]) - 0x1000 + 1
    types = []
    for i in range(n_equip):
        id_ = 0x1000 + i
        if id_ in eq_type:
            types.append(eq_type[id_])
        elif id_ < 0x10C8 or id_ >= 0x11A4:
            types.append("Weapon")
        else:
            types.append("")

    out = [
        "// Generated by tools/gen_tables.py. Do not edit by hand.\n",
        "// Names: ff12tza-utils by LuminaSapphira (MIT licence) and the PS2 IZJS rich save editor data files.\n",
        "using System.Collections.Generic;\n\n",
        "namespace FFXIISaveEditor\n{\n    static class Tables\n    {\n",
        cs_array("Items", table(md["items"], 0, 64)),
        cs_array("Equipment", table(md["equipment"], 0x1000, n_equip)),
        cs_array("EquipmentType", types),
        cs_array("Loot", table(md["loot"], 0x2000, 512)),
        cs_array("KeyItems", table(md["keyitems"], 0x8000, 512)),
        cs_array("Magicks", table(md["magicks"], 0x3000, 81)),
        cs_array("Technicks", table(md["technicks"], 0x4000, 24)),
        cs_array("Gambits", [gambits.get(0x6000 + i, "") for i in range(256)]),
        cs_array("Licenses", [licenses.get(i, "") for i in range(max(licenses) + 1)]),
        "        public static readonly Dictionary<int, string> GambitActions = new Dictionary<int, string>\n        {\n",
    ]
    out += ["            { %d, %s },\n" % (i, cs_str(n)) for i, n in sorted(actions.items())]
    out.append("        };\n    }\n}\n")

    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "editor", "Tables.cs")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(dst))


if __name__ == "__main__":
    main()
